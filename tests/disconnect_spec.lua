package.path = "game/scripts/vscripts/?.lua;game/scripts/vscripts/?/init.lua;" .. package.path
local Match = require("core.match_state")
local function eq(a,b) assert(a==b, tostring(a).." ~= "..tostring(b)) end
local m = Match.new()
eq(m:disconnect(2, 100), true)
eq(m:check_disconnect_timeout(159, 60), false)
eq(m.status, "active")
eq(m:reconnect(2), true)
eq(m:check_disconnect_timeout(500, 60), false)
eq(m:disconnect(3, 600), true)
eq(m:check_disconnect_timeout(660, 60), true)
eq(m.winner, 2)
eq(m.reason, "disconnect_forfeit")
local c = Match.new()
c:disconnect(2, 10)
c:disconnect(3, 11)
eq(c.status, "active")
eq(c:check_disconnect_timeout(69, 60), false)
eq(c:check_disconnect_timeout(70, 60), true)
eq(c.winner, 3)
local x,y = c:rating_delta(100,100)
eq(x,-25) eq(y,25)
local bad = Match.new()
eq(bad:disconnect(2, nil), false)
eq(bad:disconnect(2, 0/0), false)
eq(bad:disconnect(2, math.huge), false)
eq(bad.disconnected[2], nil)
eq(bad:disconnect(2, 100), true)
eq(bad:check_disconnect_timeout(300, 0), false)
eq(bad:check_disconnect_timeout(300, -1), false)
eq(bad:check_disconnect_timeout(0/0, 120), false)
eq(bad:check_disconnect_timeout(300, 120), true)
eq(bad.reason, "disconnect_forfeit")
local a = Match.new()
eq(a:abandon(3, 10), true)
eq(a.winner, 2)
eq(a.reason, "confirmed_abandon")
eq(a:abandon(2, 11), false)
local b = Match.new()
eq(b:abandon(2, 0/0), false)
eq(b:disconnect(2, 10), true)
eq(b:disconnect(3, 10), true)
eq(b:check_disconnect_timeout(70, 60), true)
eq(b.winner, 3)
print("disconnect_spec: OK")
