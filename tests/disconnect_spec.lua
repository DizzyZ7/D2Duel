package.path = "game/scripts/vscripts/?.lua;game/scripts/vscripts/?/init.lua;" .. package.path
local Match = require("core.match_state")
local function eq(a,b) assert(a==b, tostring(a).." ~= "..tostring(b)) end
local m = Match.new()
eq(m:disconnect(2, 100), true)
eq(m:check_disconnect_timeout(219, 120), false)
eq(m.status, "active")
eq(m:reconnect(2), true)
eq(m:check_disconnect_timeout(500, 120), false)
eq(m:disconnect(3, 600), true)
eq(m:check_disconnect_timeout(720, 120), true)
eq(m.winner, 2)
eq(m.reason, "disconnect_forfeit")
local c = Match.new()
c:disconnect(2, 10)
c:disconnect(3, 11)
eq(c.status, "cancelled")
eq(c:check_disconnect_timeout(999, 120), false)
local x,y = c:rating_delta(100,100)
eq(x,0) eq(y,0)
print("disconnect_spec: OK")
