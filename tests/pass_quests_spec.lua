package.path = "game/scripts/vscripts/?.lua;game/scripts/vscripts/?/init.lua;" .. package.path
local Q = require("core.pass_quests")
local count, xp = Q.progress("play_one", 0, "completed_match")
assert(count == 1 and xp == 40)
count, xp = Q.progress("play_one", count, "completed_match")
assert(count == 1 and xp == 0)
count, xp = Q.progress("win_one", 0, "completed_match")
assert(count == 0 and xp == 0)
count, xp = Q.progress("win_one", 0, "ranked_win")
assert(count == 1 and xp == 60)
count, xp = Q.progress("play_three", 2, "completed_match")
assert(count == 3 and xp == 80)
assert(not pcall(Q.progress, "unknown", 0, "completed_match"))
assert(not pcall(Q.progress, "play_one", -1, "completed_match"))
print("pass_quests_spec: OK")
