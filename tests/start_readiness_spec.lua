package.path = "game/scripts/vscripts/?.lua;game/scripts/vscripts/?/init.lua;" .. package.path
local Ready = require("core.start_readiness")
local a = Ready.new(100,60)
assert(a:mark(2,true))
assert(a:poll(159)=="waiting")
assert(a:mark(3,true))
assert(a:poll(161)=="ready")
local b = Ready.new(100,60)
assert(b:mark(2,true))
assert(b:poll(160)=="cancelled")
assert(not b:mark(3,true))
local c = Ready.new(100,60)
assert(c:mark(2,true))
assert(c:mark(2,false))
assert(c:mark(3,true))
assert(c:poll(159)=="waiting")
print("start_readiness_spec: OK")
