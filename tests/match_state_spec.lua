package.path = "game/scripts/vscripts/?.lua;game/scripts/vscripts/?/init.lua;" .. package.path
local Match = require("core.match_state")
local function eq(a,b) assert(a==b, tostring(a).." ~= "..tostring(b)) end
local m=Match.new()
eq(m:death(3,10),true)
eq(m.winner,2)
eq(m:death(2,11),false)
eq(m.reason,"first_kill")
local a,b=m:rating_delta(0,0)
eq(a,25) eq(b,0)
local t=Match.new()
eq(t:tower_destroyed(3,true,false,4),true)
eq(t.winner,2)
local d=Match.new()
eq(d:tower_destroyed(2,true,true,1),false)
eq(d:timeout(100,100,600,600),false)
eq(d.status,"active")
eq(d:timeout(101,100,601,601),false)
eq(d.overtime,true)
eq(d:timeout(101,100,900,900),true)
eq(d.winner,2)
local tie=Match.new()
eq(tie:timeout(100,100,600,600),false)
eq(tie:timeout(100,100,900,900),true)
eq(tie.status,"draw")
local ra,rb=tie:rating_delta(50,50)
eq(ra,0) eq(rb,0)
local c=Match.new()
eq(c:disconnect(2,100),true)
eq(c.status,"active")
eq(c:disconnect(3,101),true)
eq(c.status,"active")
eq(c:check_disconnect_timeout(160,60),true)
eq(c.winner,3)
eq(c:death(3,161),false)
local x,y=c:rating_delta(200,300)
eq(x,-25) eq(y,25)
print("match_state_spec: OK")
