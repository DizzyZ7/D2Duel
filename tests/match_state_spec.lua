package.path = "game/scripts/vscripts/?.lua;game/scripts/vscripts/?/init.lua;" .. package.path
local Match = require("core.match_state")
local function eq(a,b) assert(a==b, tostring(a).." ~= "..tostring(b)) end
local m=Match.new()
eq(m:death(3,10),true)
eq(m.winner,2)
eq(m:death(2,11),false)
eq(m.reason,"first_kill")
local a,b=m:rating_delta(0,0)
eq(a,25) eq(b,0)
local t=Match.new()
eq(t:tower_destroyed(3,true,false,4),true)
eq(t.winner,2)
local d=Match.new()
eq(d:tower_destroyed(2,true,true,1),false)
eq(d:timeout(100,100,600),false)
eq(d.status,"active")
eq(d:timeout(101,100,601),true)
eq(d.winner,2)
local c=Match.new()
eq(c:disconnect(2),true)
eq(c.status,"active")
eq(c:disconnect(3),true)
eq(c.status,"cancelled")
eq(c:death(3,3),false)
local x,y=c:rating_delta(200,300)
eq(x,0) eq(y,0)
print("match_state_spec: OK")
