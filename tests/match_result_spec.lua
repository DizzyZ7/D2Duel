package.path = "game/scripts/vscripts/?.lua;game/scripts/vscripts/?/init.lua;" .. package.path
local Match = require("core.match_state")
local Result = require("core.match_result")
local a = Match.new()
assert(not pcall(Result.snapshot, a, "test-1"))
assert(a:death(3, 42))
local r = Result.snapshot(a, "test-1")
assert(r.winner == 2 and r.reason == "first_kill" and r.status == "finished")
assert(r.ranked_eligible == false)
assert(not a:death(2, 43))
local b = Match.new()
b:disconnect(2, 10)
b:disconnect(3, 11)
local c = Result.snapshot(b, "test-2")
assert(c.status == "cancelled" and c.winner == nil and c.ranked_eligible == false)
print("match_result_spec: OK")
